CREATE TABLE security_limits(key_hash TEXT PRIMARY KEY,attempts BIGINT NOT NULL,expires_at BIGINT NOT NULL);

CREATE TABLE security_mail(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      encrypted_body TEXT NOT NULL,expires_at BIGINT NOT NULL,attempts BIGINT NOT NULL DEFAULT 0,
      next_attempt BIGINT NOT NULL DEFAULT 0,status TEXT NOT NULL DEFAULT 'PENDING');

