CREATE FUNCTION check_bot_parent() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.parent_user_id IS NOT NULL AND (NEW.bot_slot_index=1 OR NOT EXISTS(
 SELECT 1 FROM users WHERE id=NEW.parent_user_id AND parent_user_id IS NULL)) THEN
 RAISE EXCEPTION 'Invalid bot owner or slot';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER bot_parent_guard BEFORE INSERT OR UPDATE OF parent_user_id,bot_slot_index ON users
FOR EACH ROW EXECUTE FUNCTION check_bot_parent();
