/** Run a callback while recording every SQL statement the database receives. Returns the statements. */
async function recordSql(callback){
 const sql=[],query=db.query.bind(db);
 db.query=(statement,...args)=>{sql.push(String(statement));return query(statement,...args);};
 try{await callback();}finally{delete db.query;}
 return sql;
}
const WRITES=/INSERT INTO (pine_bridge_jobs|pine_bridge_attempts|pine_sources|pine_source_revisions|pine_memberships|pine_deployments|audit)\b|UPDATE (pine_memberships|pine_deployments)\b/i;
const GATE_QUERY=/operation='analyze' AND status='SUCCEEDED' ORDER BY created_at DESC LIMIT 1/;

/** POST through the real route handler, inside a transaction as the server runs a request. Returns status and body as the server maps them. */
async function post(owner,operation,body,key=randomUUID()){
 const req=Object.assign(Readable.from([Buffer.from(JSON.stringify(body))]),{method:'POST',url:'/api/quant/pine-bridge/'+operation,headers:{'idempotency-key':key}});
 const sent={};
 const json=(res,status,payload)=>{sent.status=status;sent.body=payload;};
 let handled;
 try{handled=await db.transaction(()=>pineBridgeRoutes(req,{},new URL(req.url,'http://localhost'),{id:owner},pine,json,{enabled:true}));}
 catch(error){sent.status=error.status||400;sent.body={error:error.message,...(error.code?{code:error.code}:{})};handled=true;}
 assert.equal(handled,true,'the route handled the request');
 return sent;
}

/** Real analyze through enqueue and worker. The provider stub proposes every eligible input except those named in `omit`. */
async function analysed(owner,omit=[]){
 const job=await enqueue(owner,'analyze',{bot_id:owner,pine_source:smallSource,source_name:'O1 input rule'});
 await runAll(countingProvider({buy:'buy',exit:'sell',eligible:request=>request.analysis.inputs.filter(i=>i.eligible&&!omit.includes(i.pine_variable)).map(i=>i.input_id)}));
 assert.equal((await db.transaction(()=>pine.get(owner,job.job_id))).job_status,'SUCCEEDED');
 const importId=job.pine_import_id,analysis=(await pine.source(owner,owner,importId,1)).analysis;
 return {owner,importId,analysis,analyzeJobId:job.job_id,id:name=>analysis.inputs.find(i=>i.pine_variable===name).input_id};
}
const storedProposal=async(jobId)=>(await db.prepare('SELECT result FROM pine_bridge_jobs WHERE job_id=?').get(jobId)).result.proposal.eligible_inputs;

/**
 * A second SUCCEEDED analyze job of the same source version: a clone of the first one with another proposal and creation time.
 * `offset` is milliseconds from the original job, so a later row is clearly newer and an earlier row clearly older.
 */
async function seedAnalysis(s,{offset,propose}){
 const original=await db.prepare("SELECT * FROM pine_bridge_jobs WHERE job_id=?").get(s.analyzeJobId);
 const result={...original.result,proposal:{...original.result.proposal,eligible_inputs:propose.map(s.id)}};
 const id=randomUUID(),createdAt=Number(original.created_at)+offset;
 await db.prepare("INSERT INTO pine_bridge_jobs(job_id,owner_id,bot_id,operation,idempotency_key,request_hash,request,pine_import_id,status,created_at,updated_at,deadline,attempt,result,usage) VALUES(?,?,?,'analyze',?,?,?::jsonb,?,'SUCCEEDED',?,?,?,1,?::jsonb,?::jsonb)")
  .run(id,original.owner_id,original.bot_id,'seed-'+id,hash(canonical({seed:id})),JSON.stringify(original.request),original.pine_import_id,createdAt,createdAt,Number(original.deadline)+offset,JSON.stringify(result),JSON.stringify(original.usage));
 return id;
}

const ALL=Array.from({length:10},(_,i)=>'p'+(i+1));
const INSIDE=ALL.slice(0,8);                    // p1..p8, all proposed when only p10 is omitted
const WITH_OMITTED=[...ALL.slice(0,7),'p10'];   // differs from INSIDE by exactly the omitted input
const slotFor=(input,slot)=>({slot,input_id:input.input_id,...(input.type==='int'?{min:input.effective_value-2,max:input.effective_value+2,step:1}:{min:input.effective_value-1,max:input.effective_value+1,step:.5})});
const bodyFor=(s,names)=>({bot_id:s.owner,pine_import_id:s.importId,source_version:1,selected_signals:SMALL_SIGNALS,
 parameter_slots:names.map((name,i)=>slotFor(s.analysis.inputs.find(x=>x.pine_variable===name),3+i)),
 bridge_options:{atr_multiplier:60,rr:1.5},market:{broker:'binance-global',symbol:'BTCUSDT',timeframe:'1'}});

const rows=async()=>({jobs:await count('pine_bridge_jobs'),attempts:await count('pine_bridge_attempts'),deployments:await count('pine_deployments'),generate:await count('pine_bridge_jobs',"operation='generate'")});

/**
 * One refusal on both paths. Route: 400 with the exact code. Service: the same rejection. Each: no write statement reached the
 * database (a rolled-back insert would hide an insert made before the refusal), the gate query did run (the check is reached,
 * not skipped), no job, attempt or deployment row exists, and a worker run dispatches nothing to the provider.
 */
async function assertRefused(label,s,body){
 const before=await rows();
 let sent;
 const routeSql=await recordSql(async()=>{sent=await post(s.owner,'generate',body);});
 assert.equal(sent.status,400,label+': route status');
 assert.deepEqual(sent.body,{error:'INPUT_REVIEW_REQUIRED',code:'INPUT_REVIEW_REQUIRED'},label+': route body');
 assert.deepEqual(routeSql.filter(statement=>WRITES.test(statement)),[],label+': route, no write statement before the refusal');
 assert.ok(routeSql.some(statement=>GATE_QUERY.test(statement)),label+': route reached the latest-analysis query');
 const serviceSql=await recordSql(()=>assert.rejects(enqueue(s.owner,'generate',body),{code:'INPUT_REVIEW_REQUIRED',status:400},label));
 assert.deepEqual(serviceSql.filter(statement=>WRITES.test(statement)),[],label+': service, no write statement before the refusal');
 assert.ok(serviceSql.some(statement=>GATE_QUERY.test(statement)),label+': service reached the latest-analysis query');
 const spy=generateProvider();await runAll(spy);
 assert.deepEqual(spy.calls,[],label+': zero provider calls');
 assert.deepEqual(await rows(),before,label+': no job, attempt or deployment row');
 assert.equal(await count('pine_bridge_jobs',"status IN ('QUEUED','RETRY_WAIT','RUNNING','VALIDATING')"),0,label+': nothing left runnable');
}

/** One acceptance through the route, then the real worker and the stub provider produce a DRAFT deployment bound to the named inputs. */
async function assertAccepted(label,s,names){
 const before=await rows(),body=bodyFor(s,names);
 const sent=await post(s.owner,'generate',body);
 assert.equal(sent.status,202,label+': route status '+JSON.stringify(sent.body));
 assert.equal(sent.body.job_status,'QUEUED',label);
 assert.equal((await rows()).generate,before.generate+1,label+': one generate job row');
 const spy=generateProvider();await runAll(spy);
 assert.deepEqual(spy.calls,['generate'],label+': one provider call');
 const done=await db.transaction(()=>pine.get(s.owner,sent.body.job_id));
 assert.equal(done.job_status,'SUCCEEDED',label+': '+JSON.stringify(done.diagnostic));
 const deployment=await db.prepare('SELECT state,snapshot FROM pine_deployments WHERE deployment_id=?').get(done.result.deployment_id);
 assert.equal(deployment.state,'DRAFT',label);
 assert.deepEqual(deployment.snapshot.selection.bindings.map(b=>b.input_id).sort(),names.map(s.id).sort(),label+': the deployment binds exactly the requested inputs');
}

// ---- 1: a binding outside the latest proposal is refused ------------------------------------------------------------------------
test('O1.1: a binding the latest analysis omitted is refused 400 INPUT_REVIEW_REQUIRED before any write, job or provider call',async()=>{
 const s=await analysed(await newOwner(),['p10']);
 const omitted=s.analysis.inputs.find(i=>i.pine_variable==='p10');
 // Control: p10 is code-eligible, so the refusal below is the proposal rule and not INELIGIBLE_INPUT.
 assert.equal(omitted.eligible,true,'p10 is eligible by the source scan');
 const proposed=await storedProposal(s.analyzeJobId);
 assert.equal(proposed.includes(omitted.input_id),false,'the stored proposal omits p10');
 assert.equal(proposed.length,9,'the stored proposal holds the other nine inputs');
 await assertRefused('seven proposed plus the omitted input',s,bodyFor(s,WITH_OMITTED));
 await assertRefused('the omitted input alone',s,bodyFor(s,['p10']));
 await assertRefused('the omitted input first',s,bodyFor(s,['p10',...ALL.slice(0,7)]));
});

// ---- 2: a binding set inside the proposal is accepted ---------------------------------------------------------------------------
test('O1.2: a binding set inside the proposal is accepted, queued and generated (the refusal above is not a general failure)',async()=>{
 const s=await analysed(await newOwner(),['p10']);
 await assertAccepted('eight proposed inputs',s,INSIDE);
 await assertAccepted('one proposed input',s,['p9']);
});

// ---- 3: a newer successful analysis that proposes the input makes it selectable; the newest one decides -------------------------------
test('O1.3: after a newer successful analysis proposes the omitted input the same binding is accepted; a newest one that omits it refuses it again',async()=>{
 const s=await analysed(await newOwner(),['p10']);
 const body=bodyFor(s,WITH_OMITTED);
 await assertRefused('before the newer analysis',s,body);
 await seedAnalysis(s,{offset:60000,propose:ALL});
 assert.equal((await storedProposal(s.analyzeJobId)).includes(s.id('p10')),false,'the original analysis row is unchanged');
 await assertAccepted('newer analysis proposes p10',s,WITH_OMITTED);
 await seedAnalysis(s,{offset:120000,propose:ALL.filter(name=>name!=='p10')});
 await assertRefused('newest analysis omits p10 again',s,body);
 // The analysis never makes the selection: the same proposal still accepts a different binding set.
 await assertAccepted('newest analysis, binding inside it',s,INSIDE);
});

// ---- 4: an older analysis does not override a newer one -------------------------------------------------------------------------
test('O1.4: an older analysis that proposes the input does not override a newer analysis that omits it',async()=>{
 const s=await analysed(await newOwner(),['p10']);
 const older=await seedAnalysis(s,{offset:-60000,propose:ALL});
 assert.equal((await storedProposal(older)).includes(s.id('p10')),true,'the older row proposes p10');
 assert.equal((await storedProposal(s.analyzeJobId)).includes(s.id('p10')),false,'the newer row omits p10');
 const created=async id=>Number((await db.prepare('SELECT created_at FROM pine_bridge_jobs WHERE job_id=?').get(id)).created_at);
 assert.ok(await created(older)<await created(s.analyzeJobId),'the proposing row is older');
 await assertRefused('older analysis proposes p10',s,bodyFor(s,WITH_OMITTED));
 await assertAccepted('older analysis present, binding inside the newer proposal',s,INSIDE);
});
