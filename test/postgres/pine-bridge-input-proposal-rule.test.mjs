/**
 * Owner decision O1 (docs/PINE_BRIDGE_ADAPTER_API.md, paragraph "The dropdown lists the eligible ..."): the inputs a Bridge
 * selection may bind are the ones the LATEST successful analysis of the source version proposes (proposal.eligible_inputs).
 * The server refuses a binding outside that proposal with INPUT_REVIEW_REQUIRED (src/postgres/pine-bridge.js, generate branch of
 * enqueue). A newer analysis of the same source version makes an input selectable only by proposing it; an analysis never makes
 * the selection itself.
 *   1  a generate request that binds an input the latest analysis omitted is refused 400 INPUT_REVIEW_REQUIRED, before any
 *      write, job row or provider call, on the route path and on the service path;
 *   2  a binding set inside the proposal is accepted, queued and generated by the worker;
 *   3  after a newer successful analysis proposes the omitted input, the same binding is accepted (latest analysis wins);
 *      a still newer analysis that omits it again refuses it again;
 *   4  an older analysis that proposes the input does not override a newer one that omits it.
 * The provider is a stub. The route is the real pineBridgeRoutes handler on a stream request (no socket); the service, the
 * worker and PostgreSQL are real. Expected codes and statuses are written as literals so a changed constant fails here.
 *
 * Seeding note: the public analyze enqueue allows exactly one analyze job per source version (a re-analysis needs
 * source_version = membership version + 1, and then it is a new version). A second SUCCEEDED analyze job of one source version
 * therefore cannot come from the route; tests 3 and 4 insert it as a row (a clone of the real analyze job with a changed
 * proposal and created_at). They test the generate gate against that stored state, not a route that creates it.
 * Synthetic fixtures only; nothing here says anything about the owner-private supported source or strategy performance.
 */
